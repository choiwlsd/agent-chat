import ollama


MODEL_NAME = "qwen2.5:3b"


class Agent:
    def __init__(self, name, role):
        self.name = name
        self.role = role

    def respond(self, user_message, stream_callback=None):
        system_prompt = f"""
당신의 이름은 {self.name}입니다.

당신의 역할:
{self.role}

반드시 한국어로 답변하세요.
답변은 너무 길지 않게 작성하세요.
주어진 질문을 자신의 역할에 맞게 분석하고 답변하세요.
"""

        stream = ollama.chat(
            model=MODEL_NAME,
            messages=[
                {
                    "role": "system",
                    "content": system_prompt,
                },
                {
                    "role": "user",
                    "content": user_message,
                },
            ],
            stream=True,
        )

        full_response = ""

        for chunk in stream:
            text = chunk["message"]["content"]

            if text:
                full_response += text

                if stream_callback:
                    stream_callback(text)

        return full_response


